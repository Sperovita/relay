#!/usr/bin/env bash
# Rebuild relay/STATUS.md from the frontmatter of relay/tickets/*.md.
# Lints the tickets first and refuses to write if one is broken: duplicate id, unknown status,
# missing id, title or type, filename not starting with the id. A ready ticket whose blocked-by names a ticket
# that is not done goes under Waiting, not Ready. Keeps the hand-edited "Summary:" line. Safe to run any time.
set -euo pipefail
cd "$(dirname "$0")/.."

status_file=relay/STATUS.md
summary=$(grep -m1 '^Summary:' "$status_file" 2>/dev/null || true)
[ -n "$summary" ] || summary="Summary: (one line, hand-edited; everything else here is regenerated)"

# field FILE KEY -> value from the leading --- block
field() {
  awk -v k="$2" '
    NR==1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    index($0, k ":") == 1 { sub("^" k ":[ \t]*", ""); print; exit }
  ' "$1"
}

cell() { printf '%s' "${1//|/\\|}"; }   # escape pipes inside a cell

row() {
  local f=$1
  printf '| [%s](tickets/%s) | %s | %s | %s | %s | %s |\n' \
    "$(field "$f" id)" "$(basename "$f")" \
    "$(cell "$(field "$f" title)")" \
    "$(field "$f" type)" \
    "$(field "$f" blocked-by)" \
    "$(field "$f" branch)" \
    "$(field "$f" spec)"
}

tickets() { ls relay/tickets/*.md 2>/dev/null | sort || true; }

# lint: every ticket has id, title, type and a known status; its filename starts with its id; no id
# appears twice. Names the file, exits 1.
lint() {
  local f k id st ok=true ids="" d
  for f in $(tickets); do
    for k in id title type; do
      [ -n "$(field "$f" "$k")" ] || { echo "status.sh: $f: missing $k" >&2; ok=false; }
    done
    st=$(field "$f" status)
    case "$st" in
      ready|in-progress|blocked|done) ;;
      *) echo "status.sh: $f: unknown status '$st' (ready, in-progress, blocked, done)" >&2; ok=false ;;
    esac
    id=$(field "$f" id)
    [ -z "$id" ] || ids+="$id"$'\t'"$f"$'\n'
    if [ -n "$id" ]; then
      case "$(basename "$f")" in
        "$id"-*) ;;
        *) echo "status.sh: $f: filename does not start with its id '$id'" >&2; ok=false ;;
      esac
    fi
  done
  for d in $(printf '%s' "$ids" | cut -f1 | sort | uniq -d); do
    echo "status.sh: duplicate id $d in: $(printf '%s' "$ids" | awk -F'\t' -v d="$d" '$1 == d { print $2 }' | tr '\n' ' ')" >&2
    ok=false
  done
  $ok || { echo "status.sh: not writing $status_file; fix the files above" >&2; exit 1; }
  # a blocked-by id that matches no ticket only warns; waiting() counts it as open
  local known; known=$(printf '%s' "$ids" | cut -f1)
  for f in $(tickets); do
    for d in $(field "$f" blocked-by | tr ',' ' '); do
      grep -qxF -- "$d" <<<"$known" || echo "status.sh: $f: blocked-by '$d' matches no ticket; counted as open" >&2
    done
  done
  return 0
}

# index: one "id<TAB>status" line per ticket, built once after lint
index=""
build_index() { local f; for f in $(tickets); do index+="$(field "$f" id)"$'\t'"$(field "$f" status)"$'\n'; done; }

# waiting FILE -> true when a blocked-by id names a ticket that is not done, or no ticket at all
waiting() {
  local b
  for b in $(field "$1" blocked-by | tr ',' ' '); do
    [ "$(awk -F'\t' -v b="$b" '$1 == b { print $2 }' <<<"$index")" = done ] || return 0
  done
  return 1
}

section() { # section STATUS HEADING [LIMIT]; "ready" excludes waiting tickets, "waiting" is ready ones with an open blocker
  local want=$1 heading=$2 limit=${3:-0} out="" f n=0 st
  local list; list=$(tickets)
  [ "$limit" -gt 0 ] && list=$(printf '%s\n' "$list" | sort -r)
  for f in $list; do
    [ -n "$f" ] || continue
    st=$(field "$f" status)
    case "$want" in
      ready)   [ "$st" = ready ] && ! waiting "$f" || continue ;;
      waiting) [ "$st" = ready ] && waiting "$f" || continue ;;
      *)       [ "$st" = "$want" ] || continue ;;
    esac
    out+="$(row "$f")"$'\n'
    n=$((n+1)); [ "$limit" -gt 0 ] && [ "$n" -ge "$limit" ] && break
  done
  if [ -n "$out" ]; then
    printf '## %s\n\n' "$heading"
    printf '| # | Title | Type | Blocked by | Branch | Spec |\n|---|---|---|---|---|---|\n'
    printf '%s\n' "$out"
  fi
  return 0
}

# spec_status FILE -> value of the first "Status:" line; anything but "done" counts as active
spec_status() { awk '/^Status:/ { sub(/^Status:[ \t]*/, ""); print; exit }' "$1"; }

specs() { # specs HEADING WANT_DONE(true|false)
  local heading=$1 want_done=$2 out="" s
  for s in $(ls relay/specs/*.md 2>/dev/null || true); do
    if [ "$(spec_status "$s")" = done ]; then $want_done || continue; else $want_done && continue; fi
    out+="- [$(basename "$s" .md)](specs/$(basename "$s"))"$'\n'
  done
  if [ -n "$out" ]; then
    printf '## %s\n\n' "$heading"
    printf '%s\n' "$out"
  fi
  return 0
}

lint
build_index

{
  echo "# Status"
  echo "$summary"
  echo
  echo "_Regenerated by scripts/status.sh from relay/tickets/*.md. Edit tickets, not this file, except the Summary line._"
  echo
  section in-progress "In flight"
  section blocked "Blocked"
  section ready "Ready"
  section waiting "Waiting"
  section done "Recently done" 5
  specs "Specs" false
  specs "Specs done" true
} > "$status_file.tmp"
mv "$status_file.tmp" "$status_file"
echo "wrote $status_file"
